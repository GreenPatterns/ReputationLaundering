"""Generated summary of keeper.analysis.cppr_confirm (Task 4.2b): results/analysis/cppr_confirm.md.

render_markdown takes the analysis JSON after a JSON round trip (seeds and other keys are strings) and states every
result, including the negative, inconclusive and not-evaluable ones, the integrity failures, the missing runs and the
H3a violations. Every number comes from the JSON; nothing is typed by hand.
"""
NETWORK_NAMES = {"bitcoinalpha": "Bitcoin-Alpha", "bitcoinotc": "Bitcoin-OTC", "wiki-rfa": "Wiki-RfA"}
TIER_NAMES = {"btpc": "capped BTP", "bfs": "BFS", "btpu": "uncapped BTP"}
COMPONENT_NAMES = {"a_difference": "(a) difference", "b_cut": "(b) cut", "b_suppression": "(b) suppression",
                   "difference": "best-response difference"}
READING_TEXT = {"met": "removal established", "inconclusive": "removal not established",
                "partial": "reduces the effect (measured share above)"}
STATUS_TEXT = {"ok": "**ok**: every run present passed every integrity check, and H3a holds in every capped-BTP run "
                     "used.",
               "integrity_failure": "**INTEGRITY FAILURE**: the inputs fail the checks listed below. The failing runs "
                                    "are excluded; the numbers below come from the other runs and are not "
                                    "confirmatory until the failures are resolved.",
               "code_defect": "**CODE DEFECT**: H3a is violated (listed below). The protocol requires the runs to stop, "
                              "the defect to be fixed and the runs to be repeated."}


def num(x, digits: int = 4) -> str:
    return "n/a" if x is None else f"{x:.{digits}g}"


def interval(ci) -> str:
    return "n/a" if ci is None else f"[{num(ci[0])}, {num(ci[1])}]"


def pval(p) -> str:
    return "n/a" if p is None else f"{p:.3g}"


def net(ds: str) -> str:
    return NETWORK_NAMES.get(ds, ds)


def seeds(c: dict) -> str:
    return f"{c.get('n_seeds', 0)}/{c.get('n_seeds_expected', 0)}"


def decision(c: dict) -> str:
    text = c.get("decision") or "n/a"
    if c.get("reading"):
        text += f" ({READING_TEXT[c['reading']]})"
    if c.get("contradicted"):
        text += ", contradicted"
    if c.get("not_evaluable_reason"):
        text += f" ({c['not_evaluable_reason']})"
    return text


def table(header: list, rows: list) -> list:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(r) + " |" for r in rows]


# ------------------------------------------------------------------------ sections
def header(r: dict) -> list:
    s, missing = r["settings"], r["integrity"]["missing_runs"]
    gaps = f" {len(missing)} expected runs are missing (listed below, never imputed)." if missing else ""
    lines = ["# E3/E4 confirmatory analysis (H1, H2w, H2b, H3a, H3b)", "",
             "Generated by keeper.analysis.cppr_confirm from the run files; every number comes from cppr_confirm.json.",
             "", f"Status: {STATUS_TEXT[r['status']]}{gaps}", "",
             f"Protocol: {r['protocol']['path']}, sha256 `{r['protocol']['sha256']}`.",
             f"Networks analysed: {', '.join(net(d) for d in s['networks'])}."]
    if s["networks"] != s["networks_registered"]:
        lines.append("A subset of the registered networks was analysed, so no hypothesis is evaluable as a whole.")
    note = "" if s["n_boot"] == s["n_boot_registered"] else f" (not the registered {s['n_boot_registered']:,})"
    lines += [f"Bootstrap: {s['n_boot']:,} replicates{note}, base seed {s['boot_seed']}.",
              "Holm's correction over the eight hypotheses is not applied here; the hypothesis p-values below feed the "
              "decisions step.", ""]
    return lines


def integrity_section(r: dict) -> list:
    i = r["integrity"]
    n = lambda key: f"E3 {i[key]['e3']}, E4 {i[key]['e4']}"  # noqa: E731
    lines = ["## Integrity", "",
             f"Expected runs: {n('n_expected')}. Missing: {n('n_missing')}. Excluded by an integrity failure: "
             f"{n('n_excluded')}. Used: {n('n_used')}. Code commits of the used runs: "
             + (", ".join(f"`{c}` ({k})" for c, k in i["git_commits"].items()) or "none") + ".", ""]
    if i["missing_runs"]:
        lines.append(f"Missing runs ({len(i['missing_runs'])}; reported, never imputed):")
        lines += [f"- {m['run']}: {m['reason']}" for m in i["missing_runs"]]
    else:
        lines.append("Missing runs: none.")
    lines.append("")
    if i["excluded_runs"]:
        lines.append(f"Excluded runs ({len(i['excluded_runs'])}; never used), with every violated field:")
        lines += [f"- {run}: {', '.join(fields)}" for run, fields in i["excluded_runs"].items()] + [""]
    if i["failures"]:
        lines.append(f"Integrity failures ({len(i['failures'])}):")
        lines += [f"- {f['run'] or 'protocol'}: {f['detail']}" for f in i["failures"]]
    else:
        lines.append("Integrity failures: none.")
    if i["e4_runs_without_e3_control"]:
        lines += ["", "E4 runs without a used E3 control run, so without control-adjusted gains: "
                  + ", ".join(i["e4_runs_without_e3_control"]) + "."]
    return lines + [""]


def h3a_section(r: dict) -> list:
    h = r["h3a"]
    lines = ["## H3a: Tier >= 1 admission per attack edge, capped BTP", ""]
    if h["ok"]:
        lines.append(f"Checked {h['n_runs']} runs and {h['n_groups']} groups: no group admits more fakes to Tier >= 1 "
                     "than floor(K g edge_cap_units).")
    else:
        lines.append(f"{len(h['violations'])} violations in {h['n_runs']} runs (a code defect):")
        lines += [f"- {v['run']}, {v['arm']}, group {v['group']}: {v['reason']} (admitted {v['admitted']}, "
                  f"guarantee {v['guarantee']}, bound {v['bound']})" for v in h["violations"]]
    return lines + [""]


def hypotheses_section(r: dict) -> list:
    lines = ["## Confirmatory hypotheses", ""]
    rows = []
    for name, h in r["hypotheses"].items():
        for ds, n in h["networks"].items():
            for comp, c in n["components"].items():
                rows.append([name, net(ds), COMPONENT_NAMES.get(comp, comp), num(c.get("estimate")),
                             interval(c.get("ci95")), pval(c.get("p_value")), seeds(c), decision(c)])
    lines += table(["Hypothesis", "Network", "Component", "Estimate", "95% interval", "p", "Seeds", "Decision"], rows)
    lines.append("")
    for name, h in r["hypotheses"].items():
        missing = f" Networks not analysed: {', '.join(net(d) for d in h['networks_missing'])}." \
            if h["networks_missing"] else ""
        per_net = "; ".join(f"{net(ds)} {n['status']} (p {pval(n['p_value'])})" for ds, n in h["networks"].items())
        lines.append(f"- **{name}**, {h['claim']} (rule: {h['rule']}): p = {pval(h['p_value'])}, "
                     f"{h['status_before_holm']} before Holm. {per_net}.{missing}")
    return lines + [""]


def unmet_section(r: dict) -> list:
    lines = ["## Results that do not meet their rule", ""]
    for name, h in r["hypotheses"].items():
        for ds, n in h["networks"].items():
            for comp, c in n["components"].items():
                if not c.get("met"):
                    lines.append(f"- {name}, {net(ds)}, {COMPONENT_NAMES.get(comp, comp)}: {decision(c)}; estimate "
                                 f"{num(c.get('estimate'))}, interval {interval(c.get('ci95'))}, seeds {seeds(c)}.")
    if len(lines) == 2:
        lines.append("Every component meets its rule on every analysed network.")
    return lines + [""]


def sensitivity_section(r: dict) -> list:
    unused = r["sensitivities"]["unused_targets"]
    lines = ["## Sensitivities", "",
             "Nested: the nested bootstrap replaces the crossed one. Unused targets: without the edge-level targets "
             "and bad-mouth victims of the stored seeds 0-4 (" + ", ".join(
                 f"{net(ds)} {k['edge']} and {k['trusted']}" for ds, k in unused["stored_seed_targets"].items())
             + " distinct accounts).", ""]
    mismatches = unused["replay_mismatches"]
    lines += ["Replayed draws against the E3 dumps: " + ("every used E3 run matches." if not mismatches else
              f"{len(mismatches)} mismatches, so the restriction may not be the driver's: "
              + "; ".join(f"{m['run']} {m['kind']} ({m['n_common']} of {m['n_dumped']} dumped in common)"
                          for m in mismatches) + "."), ""]
    rows = []
    for name, h in r["hypotheses"].items():
        for ds, n in h["networks"].items():
            for comp, c in n["components"].items():
                nested = c.get("sensitivity_nested") or {}
                alt = unused["hypotheses"][name][ds]["components"][comp]
                rows.append([name, net(ds), COMPONENT_NAMES.get(comp, comp),
                             f"{c.get('decision')} (p {pval(c.get('p_value'))})",
                             f"{nested.get('decision')} (p {pval(nested.get('p_value'))})",
                             f"{alt.get('decision')} (p {pval(alt.get('p_value'))}; {alt.get('n_pairs_removed')} pairs "
                             "removed)"])
    return lines + table(["Hypothesis", "Network", "Component", "Headline", "Nested", "Unused targets"], rows) + [""]


def h3b_section(r: dict) -> list:
    lines = ["## H3b: leave-one-seed-out best responses", ""]
    for ds, n in r["hypotheses"]["H3b"]["networks"].items():
        c = n["components"]["difference"]
        choice = ", ".join(f"{TIER_NAMES.get(m, m)} {cell}" for m, cell in (c.get("in_sample_choice") or {}).items())
        lines.append(f"{net(ds)} (in-sample best cells, for comparison: {choice or 'n/a'}):")
        for seed, v in (c.get("by_seed") or {}).items():
            parts = [f"{TIER_NAMES.get(m, m)} {v['choice'][m]} ({num(v['contribution'][m])})" for m in v["choice"]]
            lines.append(f"- seed {seed}: " + "; ".join(parts) + f"; endpoint {num(v['endpoint'])}")
        lines.append("")
    return lines


def _component_rows(blocks: dict, label) -> list:
    return [[*label(key), num(c.get("estimate")), interval(c.get("ci95")), seeds(c)] for key, c in blocks]


def secondary_section(r: dict) -> list:
    lines = ["## Secondary outcomes (intervals, no decision rule)", ""]
    head = ["Estimate", "95% interval", "Seeds"]
    mcc, variants, account, overshoot, amc = [], [], [], [], []
    for ds, s in r["secondary"].items():
        for tier, block in s["utility_mcc"].items():
            mcc += _component_rows(block.items(), lambda k, d=ds, t=tier: [net(d), TIER_NAMES[t], k])
        for tier, hyps in s["tier_variants"].items():
            for name, comps in hyps.items():
                variants += _component_rows(comps.items(), lambda k, d=ds, t=tier, h=name:
                                            [net(d), TIER_NAMES[t], h, COMPONENT_NAMES.get(k, k)])
        for tier, block in s["account_level"].items():
            account += _component_rows(block.items(), lambda k, d=ds, t=tier: [net(d), TIER_NAMES[t], k])
        for tier, c in s["overshoot_share"].items():
            overshoot.append([net(ds), TIER_NAMES[tier], str(c.get("n_targets_left_out")), num(c.get("estimate")),
                              interval(c.get("ci95")), seeds(c)])
        for tier, block in s["attack_minus_control"].items():
            amc += _component_rows(block.items(), lambda k, d=ds, t=tier: [net(d), TIER_NAMES[t], k])
    lines += ["### Test MCC differences (Task 1, original test snapshot)", ""]
    lines += table(["Network", "Tier", "Contrast"] + head, mcc) + [""]
    lines += ["### CPPR-BFS and uncapped CPPR-BTP on the H1/H2 endpoints", ""]
    lines += table(["Network", "Tier", "Hypothesis", "Component"] + head, variants) + [""]
    lines += ["### Account-level direct laundering (not control-adjusted)", ""]
    lines += table(["Network", "Tier", "Quantity"] + head, account) + [""]
    lines += ["### CPPR's overshoot: share of targets with a cut above 1.2", ""]
    lines += table(["Network", "Tier", "Targets left out (Plain Erasure gain <= 0)"] + head, overshoot) + [""]
    lines += ["### Attack-minus-control gains", ""]
    return lines + table(["Network", "Tier", "Arm and method"] + head, amc) + [""]


def e4_section(r: dict) -> list:
    lines = ["## E4 cells (descriptive)", "",
             "Mean control-adjusted CPPR whitewash gain per cell, with its 95% interval.", ""]
    rows, ranks = [], []
    for ds, d in r["descriptive"].items():
        labels = sorted({label for cells in d["e4_cells"].values() for label in cells} | set(d["e4_bfs_minus_capped"]))
        for label in labels:
            cell = lambda tier: d["e4_cells"].get(tier, {}).get(label)  # noqa: E731
            text = lambda c: "n/a" if c is None else f"{num(c.get('estimate'))} {interval(c.get('ci95'))}"  # noqa: E731
            rows.append([net(ds), label, text(cell("bfs")), text(cell("btpc")), text(cell("btpu")),
                         text(d["e4_bfs_minus_capped"].get(label))])
        g2 = d["best_response_g2"]
        lines.append(f"- {net(ds)}: g = 2 best-response difference (BFS minus capped BTP) {num(g2.get('estimate'))} "
                     f"{interval(g2.get('ci95'))}, seeds {seeds(g2)}.")
        for tier, cells in d["admission_by_rank"].items():
            for label, a in cells.items():
                if a["ranked"]:
                    guarantee = a["guarantee_per_group"]
                    ranks.append([net(ds), TIER_NAMES[tier], label,
                                  ", ".join(num(x, 3) for x in a["mean_admitted_per_group"]),
                                  "none (no cap)" if guarantee is None else str(guarantee)])
    lines += [""] + table(["Network", "Cell", "BFS", "capped BTP", "uncapped BTP", "BFS - capped"], rows) + [""]
    lines += ["### Admission by endorser rank (max-B(u) endorsers; exact counts)", "",
              "Mean fakes in Tier >= 1 per target group over seeds; group i holds the endorsers ranked (i - 1) g + 1 "
              "to i g by B(u).", ""]
    return lines + table(["Network", "Tier", "Cell", "Mean per group (group 1, 2, ...)", "Guarantee"], ranks) + [""]


def method_section(r: dict) -> list:
    return ["## Method", ""] + [f"- {k}: {v}" for k, v in r["method"].items()] + [""]


def render_markdown(r: dict) -> str:
    sections = (header, integrity_section, h3a_section, hypotheses_section, unmet_section, sensitivity_section,
                h3b_section, secondary_section, e4_section, method_section)
    return "\n".join(line for section in sections for line in section(r)) + "\n"
