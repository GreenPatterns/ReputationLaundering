def placement_rows_b(fed):
    out = ""
    for agg, lab in FED_AGGS:
        cells = [lab]
        for ds in FED_DATASETS:
            d = fed[ds]
            if d["status"] != "ok":
                cells += [NA, NA]
                continue
            rp, lg = d["aggs"][agg]["retained_projection"], d["aggs"][agg]["laundering_gain"]
            cells += [math_cell(f_pm(rp["mean"], rp["sd"], 3).lstrip("+")),
                      math_cell(f_pm(lg["mean"], lg["sd"]))]
        out += row([cells[0], ""] + cells[1:])
    return out


def fed_meta(fed):
    ok = [fed[ds] for ds in FED_DATASETS if fed[ds]["status"] == "ok"]
    clients = sorted({c for d in ok for c in d["clients"]})
    seeds = sorted({len(d["seeds"]) for d in ok})
    targets = sorted({t for d in ok for t in d["targets_per_seed"]})
    return clients, seeds, targets


