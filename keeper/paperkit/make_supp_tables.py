def incidental_rows(name, d):
    if d["status"] != "ok":
        return row([f"\\textbf{{{name}}}", NA, NA, NA, NA, NA])
    cohort = f"{d['cohort_size']:,}".replace(",", "{,}")
    labels = ds_label_cells(name, [f"({len(d['seeds'])} seeds, "
                                   f"$|\\mathcal{{T}}|{{=}}{cohort}$)"],
                            len(INCIDENTAL_SCENARIOS))
    out = ""
    for i, (kind, value, lab) in enumerate(INCIDENTAL_SCENARIOS):
        s = d["scenarios"][f"{kind}:{value}"]
        if s["n_seeds"] == 0:
            out += row([labels[i], lab, NA, NA, NA, NA])
            continue
        out += row([labels[i], lab,
                    math_cell(f_pct_pm(s["touched"]["mean"], s["touched"]["sd"])),
                    math_cell(f_pm(s["touched_gain"]["mean"], s["touched_gain"]["sd"])),
                    math_cell(f_pm(s["cohort_gain"]["mean"], s["cohort_gain"]["sd"])),
                    math_cell(f_pct_pm(s["flip"]["mean"], s["flip"]["sd"]))])
    return out


