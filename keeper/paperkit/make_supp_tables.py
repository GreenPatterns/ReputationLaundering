CHECKS = (("auth_role_rate", ("membership", "role", "rate_limit")),
          ("head_grad", ("fingerprint",)), ("unlearnguard_dir", ("estimation",)),
          ("pass_all", ("passes_all",)))


def verification_dataset(store, ds):
    runs = store.runs("verification", ds)
    if not runs:
        return dict(status="missing")
    kept, excluded, reproduces = [], {}, {}
    for run in runs:
        excl, _ = calibration_targets(store, run)
        laund = [q["passes_all"] for q in run["requests"] if q["kind"].startswith("launder")]
        reproduces[str(run["seed"])] = (close(float(np.mean(laund)), run["h4"]["pass_rate"])
                                        and len(laund) == run["h4"]["n"])
        hit = sorted(excl & {int(q["target"]) for q in run["requests"] if q["target"] is not None})
        excluded[str(run["seed"])] = hit
        kept += [q for q in run["requests"] if q["target"] is None or int(q["target"]) not in hit]
    groups = {}
    for key, kinds, _ in REQUEST_GROUPS:
        qs = [q for q in kept if q["kind"] in kinds]
        groups[key] = dict(n=len(qs), kinds=list(kinds), **{
            name: safe_ratio(sum(all(bool(q[c]) for c in cols) for q in qs), len(qs))
            for name, cols in CHECKS})
    laund = [q for q in kept if q["kind"].startswith("launder")]
    return dict(status="ok", seeds=[r["seed"] for r in runs], excluded_calibration_targets=excluded,
                stored_h4_reproduced=reproduces, groups=groups,
                h4_pooled_pass_all=dict(n=len(laund), rate=safe_ratio(
                    sum(bool(q["passes_all"]) for q in laund), len(laund))))


# ------------------------------------------------------------------ fed_laundering (Table 3B)
def fed_seed(run, exclude):
    recs = [r for r in run["targets"] if int(r["target"]) not in exclude]
    out = {}
    for agg, _ in FED_AGGS:
        out[agg] = dict(
            retained_projection=mean_or_none([r["aggs"][agg]["retained_projection"] for r in recs]),
            laundering_gain=mean_or_none([r["aggs"][agg]["laundering_gain"] for r in recs]))
    return out, len(recs)


def fed_dataset(store, ds):
    runs = store.runs("fed_laundering", ds)
    if not runs:
        return dict(status="missing")
    per, n_t, hits, ok = [], [], {}, {}
    for run in runs:
        full, _ = fed_seed(run, set())
        ok[str(run["seed"])] = all(
            close(full[a][k], run["summary"][a][k]["all"]["mean"])
            for a, _ in FED_AGGS for k in ("retained_projection", "laundering_gain"))
        excl, _ = calibration_targets(store, run)
        hit = sorted(excl & {int(r["target"]) for r in run["targets"]})
        hits[str(run["seed"])] = hit
        vals, n = fed_seed(run, set(hit))
        per.append(vals)
        n_t.append(n)
    return dict(status="ok", seeds=[r["seed"] for r in runs],
                clients=sorted({int(r["clients"]) for r in runs}), targets_per_seed=n_t,
                excluded_calibration_targets=hits, stored_summary_reproduced=ok,
                aggs={a: {k: stat([p[a][k] for p in per])
                          for k in ("retained_projection", "laundering_gain")}
                      for a, _ in FED_AGGS})


# ------------------------------------------------------------------ vpe (Table 4)
def vpe_key(x):
    return (x["rho"], x["granularity"], x["eps"], bool(x["small_pool_attack"]))


def vpe_dataset(store, ds):
    runs = store.runs("vpe", ds)
    if not runs:
        return dict(status="missing")
    keys = []
    for r in runs:
        for x in r["runs"]:
            if vpe_key(x) not in keys:
                keys.append(vpe_key(x))
    keys = [k for k in keys if not k[3]] + [k for k in keys if k[3]]
    points = []
    for k in keys:
        pts = [x for r in runs for x in r["runs"] if vpe_key(x) == k]
        dm = [None if x["d_t1_mcc_vs_plain"] is None else abs(x["d_t1_mcc_vs_plain"]) for x in pts]
        points.append(dict(
            rho=k[0], granularity=k[1], eps=k[2], small_pool_attack=k[3],
            m_min=sorted({x["m_min"] for x in pts}),
            all_pools_below_m_min=all(
                max((x.get("vpe_info") or {}).get("pool_sizes", {}).values(), default=0)
                < x["m_min"] for x in pts),
            edge_cut=stat([x["reduction_edge"] for x in pts]),
            account_cut=stat([x["reduction_account"] for x in pts]),
            abs_d_mcc=stat(dm),
            auc={s: stat([(x.get("linkage") or {}).get("auc", {}).get(s) for x in pts])
                 for s in VPE_SIGNALS}))
    return dict(status="ok", seeds=[r["seed"] for r in runs], points=points)


# ------------------------------------------------------------------ LaTeX helpers
def table_env(star, label, caption, colspec, header, body, tabcolsep="3pt"):
    env = "table*" if star else "table"
    width = r"\textwidth" if star else r"\columnwidth"
    return (PREAMBLE + f"\\begin{{{env}}}[!t]\n\\centering\n\\caption{{{caption}}}\n"
            f"\\label{{{label}}}\n\\scriptsize\n\\setlength{{\\tabcolsep}}{{{tabcolsep}}}\n"
            f"\\resizebox{{{width}}}{{!}}{{%\n\\begin{{tabular}}{{{colspec}}}\n\\toprule\n"
            + header + "\\midrule\n" + body + "\\bottomrule\n\\end{tabular}\n}\n"
            f"\\end{{{env}}}\n")


def row(cells):
    return " & ".join(cells) + r" \\" + "\n"


def blocks(parts):
    return "\\midrule\n".join(p for p in parts if p)


def ds_label_cells(name, extra_lines, n_rows):
    """First column: bold name on row 1, then one extra line per following row."""
    lines = [f"\\textbf{{{name}}}"] + list(extra_lines)
    return [lines[i] if i < len(lines) else "" for i in range(n_rows)]


