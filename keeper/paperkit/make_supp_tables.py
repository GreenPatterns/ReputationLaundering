# ------------------------------------------------------------------ I/O
class Store:
    """Loads result JSONs once and records every file it read (with sha256)."""

    def __init__(self, results):
        self.results = results
        self.read = {}

    def path(self, name):
        return os.path.join(self.results, name)

    def load(self, name):
        p = self.path(name)
        with open(p, "rb") as fh:
            raw = fh.read()
        self.read[p] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw)

    def seeds_present(self, family, ds):
        return [s for s in SEEDS if os.path.exists(self.path(f"{family}_{ds}_s{s}.json"))]

    def runs(self, family, ds):
        return [self.load(f"{family}_{ds}_s{s}.json") for s in self.seeds_present(family, ds)]


def calibration_targets(store, run):
    """aggregate4._cal_source: the run's recorded calibration file if it exists,
    else calibration_<ds>_s0.json in the results folder; empty if neither exists."""
    src = (run.get("calibration") or {}).get("source")
    if not (src and os.path.exists(src)):
        src = store.path(f"calibration_{run['ds']}_s0.json")
    if not os.path.exists(src):
        return set(), None
    with open(src, "rb") as fh:
        raw = fh.read()
    store.read[src] = hashlib.sha256(raw).hexdigest()
    return {int(t) for t in json.loads(raw).get("calibration_targets", [])}, src


# ------------------------------------------------------------------ statistics
def msd(xs):
    """(mean, sd ddof=1, n) over the non-None values, as aggregate4.ms."""
    xs = [float(x) for x in xs if x is not None]
    if not xs:
        return None, None, 0
    return float(np.mean(xs)), (float(np.std(xs, ddof=1)) if len(xs) > 1 else None), len(xs)


def mean_or_none(xs):
    xs = [x for x in xs if x is not None]
    return float(np.mean(xs)) if xs else None


def post_stratified_mean(values, strata, sizes):
    """metrics.post_stratified_mean: sum_h N_h/N * mean_h over pos/nopos."""
    total, tot, used = sum(sizes.values()), 0.0, 0
    for h in STRATA:
        vals = [v for v, s in zip(values, strata) if s == h and v is not None]
        if sizes.get(h, 0) == 0:
            continue
        if not vals:
            return None
        tot += sizes[h] / total * float(np.mean(vals))
        used += sizes[h]
    return float(tot) if used == total else None


def post_stratified_flip(r0, rn, strata, sizes, thr):
    """metrics.post_stratified_flip point estimate: sum_h W_h p_h."""
    r0, rn, strata = np.asarray(r0, float), np.asarray(rn, float), np.asarray(strata)
    total, est = sum(sizes.values()), 0.0
    for h, nh_pop in sizes.items():
        if nh_pop == 0:
            continue
        sel = strata == h
        if not sel.any():
            return None
        est += nh_pop / total * float(((r0[sel] < thr) & (rn[sel] >= thr)).mean())
    return float(est)


def crossings(r0, rn, thr):
    """(n, n_below, n_crossed) with crossing = r0 < thr and r0 + gain >= thr."""
    r0, rn = np.asarray(r0, float), np.asarray(rn, float)
    below = r0 < thr
    return int(len(r0)), int(below.sum()), int((below & (rn >= thr)).sum())


def close(a, b, tol=1e-9):
    if a is None or b is None:
        return a is None and b is None
    return abs(float(a) - float(b)) <= tol * max(1.0, abs(float(a)), abs(float(b)))


def stat(xs):
    m, sd, n = msd(xs)
    return dict(mean=m, sd=sd, n_seeds=n)


# ------------------------------------------------------------------ formatting
def f_signed(x, nd=4):
    return NA if x is None else f"{x:+.{nd}f}"


def f_pm(m, sd, nd=4):
    if m is None:
        return NA
    return f"{m:+.{nd}f}" + ("" if sd is None else f" \\pm {sd:.{nd}f}")


def f_pct(x, nd=1):
    return NA if x is None else f"{100 * x:.{nd}f}\\%"


def f_pct_pm(m, sd, nd=1):
    if m is None:
        return NA
    return f_pct(m, nd) + ("" if sd is None else f" \\pm {100 * sd:.{nd}f}\\%")


def f_num(x, nd=3):
    return NA if x is None else f"{x:.{nd}f}"


def math_cell(*parts):
    """'$a\\;/\\;b$', or '--' when every part is missing."""
    if all(p == NA for p in parts):
        return NA
    return "$" + r"\;/\;".join(parts) + "$"


def safe_ratio(a, b):
    return None if not b else a / b


# ------------------------------------------------------------------ probe4 (Table 1)
def direct_op(rec, op):
    return ((rec.get("direct") or {}).get("ops") or {}).get(op)


def verify_probe4(run):
    """Re-summarise the unfiltered records and compare with the stored summary
    (direct-arm gain by stratum, post-stratified gain, d_t1_mcc, U2 crossings)."""
    recs, sizes = run["targets"], run["strata_sizes"]
    stored = run["summary"]["arms"]["direct"]
    ok = True
    for op, s in stored.items():
        sel = [r for r in recs if direct_op(r, op) is not None]
        g = [direct_op(r, op)["gain"] for r in sel]
        st = [r["stratum"] for r in sel]
        ok &= close(mean_or_none(g), s["gain"]["all"]["mean"])
        for h in STRATA:
            ok &= close(mean_or_none([x for x, t in zip(g, st) if t == h]), s["gain"][h]["mean"])
        ok &= close(post_stratified_mean(g, st, sizes), s["gain_post_stratified"])
        ok &= close(mean_or_none([direct_op(r, op)["d_t1_mcc"] for r in sel]),
                    s["d_t1_mcc"]["all"]["mean"])
    u2 = [r for r in recs if direct_op(r, "exact_retrain") is not None]
    if len(u2) != len(recs) or "h1_sample_conditional" not in run["summary"]:
        return False
    r0 = [r["r0"] for r in u2]
    rn = [r["r0"] + direct_op(r, "exact_retrain")["gain"] for r in u2]
    n, nb, nc = crossings(r0, rn, DEFAULT_CUTOFF)
    hc = run["summary"]["h1_sample_conditional"]
    ok &= (n, nb, nc) == (hc["n"], hc["n_below"], hc["n_crossed"])
    return bool(ok)


def probe4_seed_values(recs, sizes, op):
    sel = [r for r in recs if direct_op(r, op) is not None]
    if not sel:
        return None
    g = [direct_op(r, op)["gain"] for r in sel]
    st = [r["stratum"] for r in sel]
    r0 = [r["r0"] for r in sel]
    rn = [a + b for a, b in zip(r0, g)]
    return dict(
        gain=mean_or_none(g),
        gain_pos=mean_or_none([x for x, t in zip(g, st) if t == "pos"]),
        gain_nopos=mean_or_none([x for x, t in zip(g, st) if t == "nopos"]),
        gain_post=post_stratified_mean(g, st, sizes),
        d_t1_mcc=mean_or_none([direct_op(r, op)["d_t1_mcc"] for r in sel]),
        seconds=mean_or_none([direct_op(r, op)["seconds"] for r in sel]),
        p_post=post_stratified_flip(r0, rn, st, sizes, DEFAULT_CUTOFF),
        cross={tau: crossings(r0, rn, tau) for tau in CUTOFFS})


def probe4_op(seeds, op):
    vals = [probe4_seed_values(s["recs"], s["sizes"], op) for s in seeds]
    vals = [v for v in vals if v is not None]
    if not vals:
        return None
    out = {k: stat([v[k] for v in vals]) for k in
           ("gain", "gain_pos", "gain_nopos", "gain_post", "d_t1_mcc", "seconds", "p_post")}
    out["cutoff"] = {}
    for tau in CUTOFFS:
        n = sum(v["cross"][tau][0] for v in vals)
        nb = sum(v["cross"][tau][1] for v in vals)
        nc = sum(v["cross"][tau][2] for v in vals)
        out["cutoff"][f"{tau:.1f}"] = dict(n_eval=n, n_below=nb, n_crossed=nc,
                                           sample=safe_ratio(nc, n), conditional=safe_ratio(nc, nb))
    return out


def probe4_dataset(store, ds, allow_partial):
    present = store.seeds_present("probe4", ds)
    if not present or (len(present) < SPEC_SEEDS and not allow_partial):
        return dict(status="pending", seeds_present=present)
    seeds = []
    for run in store.runs("probe4", ds):
        excl, src = calibration_targets(store, run)
        hit = sorted(excl & {int(r["target"]) for r in run["targets"]})
        seeds.append(dict(seed=run["seed"], sizes=run["strata_sizes"], hit=hit, cal_source=src,
                          recs=[r for r in run["targets"] if int(r["target"]) not in hit],
                          reproduces_stored_summary=verify_probe4(run),
                          gpu=(run.get("provenance") or {}).get("gpu_name"),
                          code=((run.get("provenance") or {}).get("code_sha256") or "")[:12]))
    return dict(status="ok", seeds=[s["seed"] for s in seeds],
                n_eval_per_seed=[len(s["recs"]) for s in seeds],
                excluded_calibration_targets={str(s["seed"]): s["hit"] for s in seeds},
                calibration_source=sorted({s["cal_source"] or "" for s in seeds}),
                reproduces_stored_summary={str(s["seed"]): s["reproduces_stored_summary"]
                                           for s in seeds},
                gpu={str(s["seed"]): s["gpu"] for s in seeds},
                code_sha256_12={str(s["seed"]): s["code"] for s in seeds},
                strata_sizes=seeds[0]["sizes"],
                ops={op: probe4_op(seeds, op) for op, _ in OPS})


# ------------------------------------------------------------------ incidental (Table 2)
def scenario_matches(sc, kind, value):
    if sc["kind"] != kind:
        return False
    key = "top_r" if kind == "prolific" else "rate"
    return math.isclose(float(sc["params"][key]), float(value))


def incidental_seed(run, kind, value):
    draws = [sc for sc in run["scenarios"] if scenario_matches(sc, kind, value)]
    if not draws:
        return None
    ops = [sc["ops"][INCIDENTAL_OP] for sc in draws]
    return dict(
        n_draws=len(draws),
        touched=mean_or_none([safe_ratio(sc["n_targets_lost_distrust"], sc["n_targets"])
                              for sc in draws]),
        touched_gain=mean_or_none([o["gain_touched"]["all"]["mean"] for o in ops]),
        cohort_gain=mean_or_none([o["gain"]["all"]["mean"] for o in ops]),
        flip=mean_or_none([o["flip"]["all"]["literal"] for o in ops]),
        n_touched_draws_with_targets=sum(o["gain_touched"]["all"]["n"] > 0 for o in ops))


def incidental_dataset(store, ds):
    runs = store.runs("incidental", ds)
    if not runs:
        return dict(status="missing")
    out = dict(status="ok", seeds=[r["seed"] for r in runs],
               cohort_size=runs[0]["cohort_size"], operator=INCIDENTAL_OP, scenarios={})
    for kind, value, _ in INCIDENTAL_SCENARIOS:
        vals = [v for v in (incidental_seed(r, kind, value) for r in runs) if v is not None]
        out["scenarios"][f"{kind}:{value}"] = dict(
            n_seeds=len(vals), draws_per_seed=[v["n_draws"] for v in vals],
            **{k: stat([v[k] for v in vals])
               for k in ("touched", "touched_gain", "cohort_gain", "flip")})
    return out


