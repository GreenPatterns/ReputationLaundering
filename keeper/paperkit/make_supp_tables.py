def eps_label(eps):
    return r"\infty" if eps is None else f"{eps:g}"


def vpe_auc_cell(p):
    vals = [p["auc"][s]["mean"] for s in VPE_SIGNALS]
    if all(v is None for v in vals):
        return NA
    return "$" + "/".join(NA if v is None else f"{v:.3f}".lstrip("0") for v in vals) + "$"


def vpe_rows(vpe, dss):
    ref = vpe[dss[0]]["points"]
    keys = [(p["rho"], p["granularity"], p["eps"], p["small_pool_attack"]) for p in ref]
    out, prev_small = "", False
    for k in keys:
        if k[3] and not prev_small:
            out += "\\midrule\n"
            m = sorted({m for ds in dss for p in vpe[ds]["points"] if p["small_pool_attack"]
                        for m in p["m_min"]})
            out += (f"\\multicolumn{{{3 + 4 * len(dss)}}}{{@{{}}l@{{}}}}{{\\textit{{Adaptive "
                    f"small-pool attack (no honest background, noise on pools with fewer than "
                    f"$m_{{\\min}}{{=}}{'/'.join(map(str, m))}$ raters)}}}} \\\\\n")
        prev_small = k[3]
        cells = [f"${k[0]:g}$", f"${k[1]}$", f"${eps_label(k[2])}$"]
        for ds in dss:
            p = next((q for q in vpe[ds]["points"]
                      if (q["rho"], q["granularity"], q["eps"], q["small_pool_attack"]) == k), None)
            if p is None:
                cells += [NA] * 4
                continue
            cells += [math_cell(f_pct(p["edge_cut"]["mean"])),
                      math_cell(f_pct(p["account_cut"]["mean"])),
                      math_cell(f_num(p["abs_d_mcc"]["mean"], 4)), vpe_auc_cell(p)]
        out += row(cells)
    return out


