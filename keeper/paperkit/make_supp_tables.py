def cutoff_cell(c, post=None):
    if c is None:
        return NA
    count = f"[{c['n_crossed']}/{c['n_eval']}]"
    samp = f_pct(c["sample"]) + r"\;" + count
    parts = [samp] + ([f_pct(post)] if post is not None else []) + [f_pct(c["conditional"])]
    return math_cell(*parts)


def strata_rows(ds, name, d):
    n_cols = 11
    if d["status"] != "ok":
        labels = ds_label_cells(name, [r"(\pending{})"], len(OPS))
        return "".join(row([labels[i], lab] + [PENDING] * (n_cols - 2))
                       for i, (_, lab) in enumerate(OPS))
    n_eval = sum(d["n_eval_per_seed"])
    n_cal = len({t for v in d["excluded_calibration_targets"].values() for t in v})
    extra = [f"({len(d['seeds'])} seeds, $N_{{\\mathrm{{eval}}}}{{=}}{n_eval}$)",
             f"($|\\mathcal{{T}}_{{\\mathrm{{cal}}}} \\cap \\mathcal{{T}}|{{=}}{n_cal}$ excl.)"]
    labels = ds_label_cells(name, extra, len(OPS))
    out = ""
    for i, (op, lab) in enumerate(OPS):
        o = d["ops"].get(op)
        if o is None:
            out += row([labels[i], lab] + [NA] * (n_cols - 2))
            continue
        cut = o["cutoff"]
        out += row([labels[i], lab,
                    math_cell(f_pm(o["gain"]["mean"], o["gain"]["sd"])),
                    math_cell(f_signed(o["gain_post"]["mean"])),
                    math_cell(f_signed(o["gain_pos"]["mean"])),
                    math_cell(f_signed(o["gain_nopos"]["mean"])),
                    *[cutoff_cell(cut[f"{t:.1f}"], post=o["p_post"]["mean"]
                                  if t == DEFAULT_CUTOFF else None) for t in CUTOFFS],
                    math_cell(f_signed(o["d_t1_mcc"]["mean"])),
                    math_cell(f_num(o["seconds"]["mean"], 2))])
    return out


